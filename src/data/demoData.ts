export function createFallbackClimateForFarm(farm: Farm): FarmClimateProfile {
  const latAbs = Math.abs(farm.coordinates.lat);
  const baseTemp = clampTemp(25 - latAbs * 0.14);
  const rainScale = farm.irrigation === 'Dryland (Rainfed Only)' ? 0.72 : 1.0;

  return {
    farmId: farm.id,
    sourceLabel: 'Demonstration Dataset (Interpolated Local Profile)',
    isExternalLive: false,
    frostFreeDays: Math.round(220 - latAbs * 1.3),
    annualRainfallMm: Math.round(860 * rainScale),
    meanGrowingTempC: Number(baseTemp.toFixed(1)),
    droughtRiskLevel: rainScale < 0.8 ? 'Elevated' : 'Low',
    monthly: MONTHS.map((month, i) => {
      const seasonalOffset = Math.sin(((i - 3) / 12) * Math.PI * 2) * 10;
      const avg = Number((baseTemp - 4 + seasonalOffset).toFixed(1));
      const rain = Math.round((55 + Math.sin(((i - 2) / 12) * Math.PI * 2) * 38) * rainScale);
      return {
        month,
        rainfallMm: Math.max(12, rain),
        baselineRainfallMm: Math.max(15, Math.round(rain * 0.96)),
        tempAvgC: avg,
        tempMinC: Number((avg - 5.2).toFixed(1)),
        tempMaxC: Number((avg + 5.6).toFixed(1)),
        evapotranspirationMm: Math.max(15, Math.round(65 + seasonalOffset * 5.2)),
        gdd: Math.max(0, Math.round((avg - 10) * 30)),
      };
    }),
  };
}

function clampTemp(v: number): number {
  return Math.max(12, Math.min(28, v));
}

